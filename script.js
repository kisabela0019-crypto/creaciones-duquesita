/* =========================
VARIABLES
========================= */

let carrito = new Map();

const contenedorProductos = document.getElementById("productos");
const listaCarrito = document.getElementById("lista-carrito");
const totalCarrito = document.getElementById("total");
const cantidadCarrito = document.getElementById("cantidad-carrito");

/* =========================
FORMATEAR PRECIO
========================= */

function formatearPrecio(valor){

return new Intl.NumberFormat("es-CO",{
style:"currency",
currency:"COP",
minimumFractionDigits:0
}).format(valor);

}

/* =========================
RENDER PRODUCTOS
========================= */

function renderProductos(lista = productos){

contenedorProductos.innerHTML = "";

lista.forEach(p => {

contenedorProductos.innerHTML += `

<div class="producto">

<img src="${p.img}" alt="${p.nombre}">

<h3>${p.nombre}</h3>

<span class="categoria-card">
${p.categoria}
</span>

<p class="descripcion-card">
${p.descripcion}
</p>

<p>${formatearPrecio(p.precio)}</p>

<button onclick="agregarAlCarrito(${p.id})">
Agregar al carrito
</button>

</div>

`;

});

}

/* =========================
AGREGAR AL CARRITO
========================= */

function agregarAlCarrito(id){

const producto = productos.find(p => p.id === id);

if(carrito.has(id)){

carrito.get(id).cantidad++;

}else{

carrito.set(id,{
...producto,
cantidad:1
});

}

actualizarCarrito();

}

/* =========================
ACTUALIZAR CARRITO
========================= */

function actualizarCarrito(){

listaCarrito.innerHTML = "";

let total = 0;
let cantidad = 0;

carrito.forEach(item => {

total += item.precio * item.cantidad;

cantidad += item.cantidad;

listaCarrito.innerHTML += `

<li class="item-carrito">

<div>

<strong>${item.nombre}</strong>

<br>

Cantidad: ${item.cantidad}

</div>

<button onclick="eliminarDelCarrito(${item.id})">
❌
</button>

</li>

`;

});

totalCarrito.textContent = formatearPrecio(total);

cantidadCarrito.textContent = cantidad;

}

/* =========================
ELIMINAR DEL CARRITO
========================= */

function eliminarDelCarrito(id){

if(!carrito.has(id)) return;

const item = carrito.get(id);

if(item.cantidad > 1){

item.cantidad--;

}else{

carrito.delete(id);

}

actualizarCarrito();

}

/* =========================
VACIAR CARRITO
========================= */

function vaciarCarrito(){

carrito.clear();

actualizarCarrito();

}

/* =========================
FINALIZAR COMPRA
========================= */

function finalizarCompra(){

if(carrito.size === 0){

alert("Tu carrito está vacío");

return;

}

document.getElementById("modalPago").style.display = "flex";

const paypalContainer = document.getElementById("paypal-button-container");

paypalContainer.style.display = "block";

paypalContainer.innerHTML = "";

let total = 0;

carrito.forEach(item => {
total += item.precio * item.cantidad;
});

paypal.Buttons({

createOrder: function(data, actions){

return actions.order.create({

purchase_units: [{
amount: {
value: (total / 4000).toFixed(2)
}
}]

});

},

onApprove: function(data, actions){

return actions.order.capture().then(function(details){

alert("Pago realizado con éxito 💖");

vaciarCarrito();

cerrarModal();

});

}

}).render('#paypal-button-container');

}

/* =========================
CERRAR MODAL
========================= */

function cerrarModal(){

document.getElementById("modalPago").style.display = "none";

}

/* =========================
FILTRAR CATEGORÍA
========================= */

function filtrarCategoria(cat, boton){

const filtrados = cat === "todos"

? productos

: productos.filter(
p => p.categoria === cat
);

renderProductos(filtrados);

document
.querySelectorAll(".categorias-nav button")
.forEach(btn =>
btn.classList.remove("activo")
);

boton.classList.add("activo");

}

/* =========================
INICIAR
========================= */

renderProductos();
